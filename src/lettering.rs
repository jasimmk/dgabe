/// Measures the nominal glyph bounds in unscaled pixels, excluding final spacing.
#[must_use]
pub fn measure(text: &str) -> (u32, u32) {
    if text.is_empty() {
        return (0, 0);
    }
    let mut width = 0_u32;
    let mut line_width = 0_u32;
    let mut height = GLYPH_HEIGHT;
    for character in text.chars() {
        if character == '\n' {
            width = width.max(line_width.saturating_sub(1));
            line_width = 0;
            height = height.saturating_add(LINE_ADVANCE);
        } else {
            line_width = line_width.saturating_add(ADVANCE);
        }
    }
    (width.max(line_width.saturating_sub(1)), height)
}

/// Visits lit pixels relative to the top left; the caller applies scale and color.
/// No allocation, SDL type, texture, or external font is required.
pub fn for_each_pixel(text: &str, mut paint: impl FnMut(u32, u32)) {
    let mut x = 0_u32;
    let mut y = 0_u32;
    for character in text.chars() {
        if character == '\n' {
            x = 0;
            y = y.saturating_add(LINE_ADVANCE);
            continue;
        }
        for (row, bits) in (0_u32..GLYPH_HEIGHT).zip(glyph(character)) {
            for column in 0_u32..GLYPH_WIDTH {
                if bits & (1 << (GLYPH_WIDTH - 1 - column)) != 0 {
                    paint(x.saturating_add(column), y.saturating_add(row));
                }
            }
        }
        x = x.saturating_add(ADVANCE);
    }
}
